CREATE TABLE IF NOT EXISTS tb_pelanggan (
  id_pelanggan integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  password text NOT NULL,
  nama_pelanggan text NOT NULL,
  telepon text NOT NULL
);

CREATE TABLE IF NOT EXISTS tb_produk (
  id_produk integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_produk varchar(40) NOT NULL,
  harga_produk integer NOT NULL,
  berat_produk integer NOT NULL,
  foto_produk varchar(40) NOT NULL,
  deskripsi_produk text NOT NULL
);

