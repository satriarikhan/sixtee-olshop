CREATE TABLE IF NOT EXISTS tb_pembelian (
  id_pembelian integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pelanggan integer NOT NULL,
  id_prov varchar(2) NOT NULL,
  kabupaten text NOT NULL DEFAULT '',
  kecamatan text NOT NULL DEFAULT '',
  tanggal_pembelian date NOT NULL,
  total_pembelian integer NOT NULL,
  tarif integer NOT NULL,
  alamat varchar(50) NOT NULL,
  status varchar(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS tb_pembelian_produk (
  id_pembelian_produk integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pembelian integer NOT NULL,
  id_produk integer NOT NULL,
  jumlah integer NOT NULL
);

CREATE TABLE IF NOT EXISTS tb_pembayaran (
  id_pembayaran integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pembelian integer NOT NULL,
  nama varchar(30) NOT NULL,
  bank varchar(30) NOT NULL,
  jumlah integer NOT NULL,
  tanggal date NOT NULL,
  bukti varchar(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS ulasan (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rating integer NOT NULL,
  coment text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_pembelian_pelanggan ON tb_pembelian (id_pelanggan);
CREATE INDEX IF NOT EXISTS idx_pembelian_produk_pembelian ON tb_pembelian_produk (id_pembelian);
CREATE INDEX IF NOT EXISTS idx_pembayaran_pembelian ON tb_pembayaran (id_pembelian);
